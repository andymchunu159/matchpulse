"use client";

import { useState } from "react";

export default function PredictionsTestPage() {
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<string>("");
  const [error, setError] = useState<string>("");
  const [errorTitle, setErrorTitle] = useState<string>("");
  const [cached, setCached] = useState<boolean | null>(null);

  async function generatePrediction() {
    if (loading) {
      return;
    }

    setLoading(true);
    setResult("");
    setError("");
    setErrorTitle("");
    setCached(null);

    try {
      const response = await fetch("/api/predictions", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          homeTeam: "Liverpool",
          awayTeam: "Arsenal",
          competition: "Premier League",
          fixtureDate: "2026-08-15",
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        if (response.status === 503) {
          setErrorTitle("Prediction Temporarily Unavailable");
          setError(
            data.message ??
              "Our prediction engine is currently experiencing high demand. Please try again shortly.",
          );
        } else {
          setErrorTitle("Prediction Unavailable");
          setError(
            data.message ??
              data.error ??
              "We were unable to generate a prediction right now. Please try again shortly.",
          );
        }

        return;
      }

      setCached(data.cached === true);
      setResult(JSON.stringify(data, null, 2));
    } catch {
      setErrorTitle("Connection Error");
      setError(
        "We couldn't connect to the prediction service. Please check your connection and try again.",
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <main className="min-h-screen p-8">
      <div className="mx-auto max-w-4xl">
        <h1 className="text-3xl font-bold">
          MatchPulse Prediction Test
        </h1>

        <p className="mt-2">
          Temporary Gemini + Tavily + Supabase cache integration test.
        </p>

        <button
          type="button"
          onClick={generatePrediction}
          disabled={loading}
          className="mt-6 rounded-lg border px-5 py-3 disabled:cursor-not-allowed disabled:opacity-50"
        >
          {loading
            ? "Generating Prediction..."
            : "Generate Prediction"}
        </button>

        {cached !== null ? (
          <div className="mt-6 rounded-lg border p-4">
            <p className="font-semibold">
              {cached
                ? "⚡ Cached Prediction"
                : "🧠 Fresh Prediction"}
            </p>

            <p className="mt-1 text-sm">
              {cached
                ? "This prediction was served directly from the Supabase cache."
                : "This prediction was generated by the Tavily → Gemini pipeline and saved to the Supabase cache."}
            </p>
          </div>
        ) : null}

        <div className="mt-6">
          {error ? (
            <div className="rounded-lg border p-4">
              <h2 className="font-semibold">
                {errorTitle || "Prediction Error"}
              </h2>

              <p className="mt-2 text-sm">
                {error}
              </p>
            </div>
          ) : null}

          {result ? (
            <pre className="mt-6 overflow-auto rounded-lg border p-4 text-sm">
              {result}
            </pre>
          ) : null}
        </div>
      </div>
    </main>
  );
}